"""Build the CoD1 half of the DOD-SP WW2 NPC animation pack.

Input: a Crowbar decompile of the CoD1 'assault' port (3ds Max biped bones).
Output: npc_ww2_anims_cod1.qc + SMDs retargeted onto the DoD German skeleton
(see retarget_cod1.py), compiling to models/german/npc_ww2_anims_cod1.mdl.

usage: build_cod1_pack.py <assault_dir> <dod_player_shared_dir> <german_rifleman_reference.smd> <ww2_skeleton.smd> <out_dir>
"""
import os, re, sys, shutil
sys.path.insert(0, os.path.dirname(__file__))
from cod1_setup import make_retargeter
from upper_layer import weightlist_lines, upper_sequence, ikchain_lines, hand_release_lines, rebase_upper, walkframe_lines
from smd import SMD

UPPER_PAINS = {'pain_lshoulder': 'ACT_WW2_UPPER_PAIN_LSHOULDER', 'pain_rshoulder': 'ACT_WW2_UPPER_PAIN_RSHOULDER',
               'pain_hunch': 'ACT_WW2_UPPER_PAIN_HUNCH', 'crouch_pain': 'ACT_WW2_UPPER_CROUCH_PAIN'}

# Full-body pains (played when he's standing or crouched still): extract their motion.
FULL_BODY_PAINS = {'pain_lshoulder', 'pain_rshoulder', 'pain_hunch', 'crouch_pain', 'pain_falltohand', 'pain_leg'}

SRC, DOD_DIR, DOD_REF, SKELETON, OUT = sys.argv[1:6]
qc = open(os.path.join(SRC, 'assault.qc'), encoding='latin1').read().replace('\r\n', '\n')

WANT = re.compile(r'^(pain_|crouch_pain|prone_pain|stumble|wounded_|death_|crouch_death|cn_|hide|stand2hide|crouch2hide|'
                  r'aim2hide|grenade_return|crouch_grenade_return|grenade_kick|grenadehide|grenade_throw|'
                  r'crouch_grenade_throw|melee|crouch_melee|wave_|dodge_|mantle_|jump_down|trav_|medic_|rescue|'
                  r'rescued|fallen_|downed_|carried_fall|rechamber|crouch_rechamber|crouch2prone|crouchrun2prone|'
                  r'prone2crouch|prone_|plant_bomb|run_hurt|walk_hurt|'
                  r'crouch_twitch|idle_twitch)')     # A4a: flinching in place under fire, crouched / standing

# Activities the base HL2 AI already asks for: keep them where the animation fits.
KEEP_HL2 = {
    'pain_lshoulder': 'ACT_FLINCH_LEFTARM', 'pain_rshoulder': 'ACT_FLINCH_RIGHTARM', 'pain_hunch': 'ACT_FLINCH_STOMACH',
    'pain_leg': 'ACT_FLINCH_LEFTLEG',
    'death_frontspin': 'ACT_DIESIMPLE', 'death_headcollapse': 'ACT_DIE_HEADSHOT', 'death_topple': 'ACT_DIESIMPLE',
    'death_leghit': 'ACT_DIESIMPLE', 'death_lowerback': 'ACT_DIEBACKWARD', 'death_lowertorso': 'ACT_DIESIMPLE',
    'death_neck': 'ACT_DIESIMPLE', 'death_nerve': 'ACT_DIESIMPLE', 'death_dropinplace': 'ACT_DIESIMPLE',
    'death_legs': 'ACT_DIESIMPLE', 'death_neck_thrash': 'ACT_DIESIMPLE',
}
EXTRA = {'pain_leg': ['ACT_FLINCH_RIGHTLEG']}     # one animation, second activity

# CoD1 sound events -> sounds this mod has (others dropped)
SOUND_MAP = {'COD1.BodyFall': 'AI_BaseNPC.BodyDrop_Heavy'}

def activity_for(name):
    if name in KEEP_HL2: return KEEP_HL2[name]
    n = re.sub(r'\d+$', '', name)                  # stumble1 -> stumble, crouch_death3 -> crouch_death
    n = re.sub(r'^death_crouchrun_.*', 'death_crouchrun', n)
    return 'ACT_WW2_' + n.upper()

seqs = []
for m in re.finditer(r'^\$sequence "([^"]+)" \{\n(.*?)^\}', qc, re.M | re.S):
    if WANT.match(m.group(1)):
        seqs.append((m.group(1), m.group(2)))

poseparams = {m.group(1): m.group(0) for m in re.finditer(r'^\$poseparameter "([^"]+)".*$', qc, re.M)}

os.makedirs(OUT, exist_ok=True)
shutil.copy(SKELETON, os.path.join(OUT, 'ww2_skeleton.smd'))
rt = make_retargeter(SRC, DOD_DIR, DOD_REF)

converted = {}
def convert(smd):
    if smd not in converted:
        dst = 'c1_' + smd.replace('assault_anim_@', '')
        converted[smd] = (dst, rt.convert(os.path.join(SRC, smd), os.path.join(OUT, dst)))
    return converted[smd][0]

L = ['// DOD-SP WW2 NPC animation pack, part 2 (generated by build_cod1_pack.py - edit the generator, not this file)',
     '// Animations: Call of Duty 1 German "assault" NPC set (via a Source port), retargeted from the 3ds Max',
     '// biped onto the DoD:S German skeleton. For private testing only.',
     '$modelname "german\\npc_ww2_anims_cod1.mdl"',
     '$cdmaterials "models\\german\\"',
     '$bodygroup "skeleton"\n{\n\tstudio "ww2_skeleton.smd"\n}']
used_params = []
body = []
rows = []
for name, b in seqs:
    lines = [l.strip() for l in b.split('\n') if l.strip()]
    smds = [l.strip('"') for l in lines if l.startswith('"')]
    keep = []
    for l in lines:
        if l.startswith('"') or l.startswith('activity'): continue
        if l.startswith('weightlist'): continue               # face weightlists only
        ev = re.match(r'\{ event AE_CL_PLAYSOUND (\d+) "([^"]+)" \}', l)
        if ev:
            snd = SOUND_MAP.get(ev.group(2))
            if snd: keep.append(f'{{ event AE_CL_PLAYSOUND {ev.group(1)} "{snd}" }}')
            continue
        if l.startswith('{'): continue
        mm = re.match(r'blend "([^"]+)"', l)
        if mm and mm.group(1) not in used_params: used_params.append(mm.group(1))
        keep.append(l)
    acts = [activity_for(name)] + EXTRA.get(name, [])
    for k, act in enumerate(acts):
        seqname = 'c1_' + name + ('' if k == 0 else f'_{k}')
        body.append(f'$sequence "{seqname}" {{')
        for s in smds: body.append(f'\t"{convert(s)}"')
        body.append(f'\tactivity "{act}" 1')
        for l in keep: body.append('\t' + l)
        if len(smds) == 1:
            for l in hand_release_lines(converted[smds[0]][1]): body.append('\t' + l)
            if name in FULL_BODY_PAINS:
                for l in walkframe_lines(os.path.join(OUT, converted[smds[0]][0])): body.append('\t' + l)
        body.append('}')
        rows.append((seqname, act, smds[0], converted[smds[0]][1]))

for p in used_params: L.append(poseparams[p])
L += ikchain_lines()
L += weightlist_lines(SMD(DOD_REF).nodes)
for name, b in seqs:
    if name in UPPER_PAINS:
        smd = [l.strip().strip('"') for l in b.split('\n') if l.strip().startswith('"')][0]
        sn = 'c1_upper_' + name
        act = UPPER_PAINS[name]
        stance = os.path.join(DOD_DIR, 'dod_player_shared_anim_@' + ('CrouchAim_MP40.smd' if 'CROUCH' in act else 'StandAim_MP40.smd'))
        usmd = 'u_' + converted[smd][0]
        turn = rebase_upper(os.path.join(OUT, converted[smd][0]), os.path.join(OUT, usmd), stance)
        print(f'  overlay {sn}: turned {turn:.0f} deg onto DoD\'s {os.path.basename(stance)[24:-4]}')
        body += upper_sequence(sn, usmd, act, converted[smd][1])
        rows.append((sn, UPPER_PAINS[name], smd, converted[smd][1]))
L.append('')
L += body
open(os.path.join(OUT, 'npc_ww2_anims_cod1.qc'), 'w', newline='\r\n').write('\n'.join(L) + '\n')
with open(os.path.join(OUT, 'SEQUENCES_COD1.txt'), 'w', newline='\r\n') as f:
    f.write('sequence\tactivity\tsource\tframes\n')
    for r in rows: f.write('\t'.join(str(x) for x in r) + '\n')
print('sequences', len(rows), 'smds', len(converted), 'pose params', used_params)
