"""Every CoD2 vehicle tag (bone) in OUR game frame - the one source for where guns, hatches, seats and parts sit.

    python3 cod2_tags.py <CoD2 pack dir (xmodelparts/ xmodelsurfs/)> <out .txt>

The owner's conversions (models/cod2/vehicles/*) are CoD2's meshes x PORT_SCALE, facing +X in game like CoD (game
x = CoD x, game y = CoD y = the vehicle's left, z up). Fitted per vehicle against CoD's own mesh (cod2models.zip,
2026-11-20): scale 1.028 for panzer2 / tiger / sherman / crusader / armoredcar, median miss 0.03-0.05 units; every
turret model's origin = CoD's tag_turret x 1.028 (miss <= 0.04). So a tag here is exact, not an estimate.
Per tag: its parent group (hull / turret / barrel, by what it rides on), the game-frame position on the hull, and for
turret/barrel tags the position in the TURRET model's frame (turret at yaw 0) - what dodsp_vehicles.txt's turret
keys use. Also: which bones carry mesh (moving parts) and how many triangles.
"""
import os, sys, collections, numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cod2_xmodel import parts, surfs

PORT_SCALE = 1.028
VEHICLES = [      # our type, CoD2 xmodelparts / xmodelsurfs name (LOD 0)
    ('panzer2', 'vehicle_german_panzer_21'), ('tiger', 'tiger_i1'), ('sherman', 'vehicle_sherman_tank1'),
    ('crusader', 'vehicle_crusader21'), ('armoredcar', 'vehicle_german_armored_car1'), ('carrier', 'universal_carrier_new1'),
    ('halftrack', 'halftrack_mg1'), ('blitz', 'opel_blitz1'), ('kubel', 'vehicle_kubelwagen1'), ('buffalo', 'ltv4_buffalo1')]
TURRET_ROOTS = ('turret_recoil', 'tag_turret', 'turret_animate')

def group(B, i):
    names = []
    while i >= 0:
        names.append(B[i]['name']); i = B[i]['parent']
    if any(n in ('tag_barrel', 'barrel_recoil', 'barrel_animate') for n in names): return 'barrel'
    if any(n in TURRET_ROOTS for n in names[1:]) or names[0] in ('turret_recoil', 'turret_animate'): return 'turret'
    return 'hull'

def main(pack, out):
    lines = ['// Generated by dodsp_tools/vehicle_preview/cod2_tags.py from the owner\'s CoD2 pack - do not edit by hand.',
             '// Game frame: x front, y left, z up, units; = CoD2 x %.3f. turret-frame = relative to the turret model\'s origin.' % PORT_SCALE]
    for veh, cod in VEHICLES:
        pp, sp = os.path.join(pack, 'xmodelparts', cod), os.path.join(pack, 'xmodelsurfs', cod)
        if not os.path.exists(pp): continue
        B = parts(pp)
        tur = next((b for b in B if b['name'] == 'tag_turret'), None)
        tri = collections.Counter()
        if os.path.exists(sp):
            for s in surfs(sp):
                for t in s['tris']:
                    bn = [s['verts'][i]['bone'] for i in t]; tri[max(set(bn), key=bn.count)] += 1
        lines.append('\n%s (CoD2 %s, %d bones, %d triangles)' % (veh, cod, len(B), sum(tri.values())))
        for i, b in enumerate(B):
            if 'wheel' in b['name']: continue
            g = group(B, i); p = b['t'] * PORT_SCALE
            rel = ('  turret-frame %7.1f %7.1f %7.1f' % tuple(p - tur['t'] * PORT_SCALE)) if (tur is not None and g != 'hull') else ''
            mesh = ('  mesh %d tris' % tri[i]) if tri[i] else ''
            lines.append('  %-26s %-6s game %7.1f %7.1f %7.1f%s%s' % (b['name'], g, p[0], p[1], p[2], rel, mesh))
    open(out, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote', out)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
