"""Which material of a vehicle is its TRACK, which texture axis runs along it, and how fast - measured from the mesh.

    python3 tread_scroll.py <vehicle model dir> [model ...]          report
    python3 tread_scroll.py <vehicle model dir> --write <out .txt>    the table the game reads (scripts/dodsp_treads.txt)

The CoD2 conversion's materials named the scroll proxy by hand, and on the Tiger and Sherman it sat on the wheel
markings, scrolling the wrong way (owner, 2026-11-20); the halftrack's tread had none. So the proxy's material, axis
and rate are read from the geometry instead: a track is a loop - along its BOTTOM run (on the ground) and its TOP run the
texture coordinate changes steadily along the vehicle, with opposite signs (the strip wraps round), on both sides.
Wheel markings go round a wheel and show no steady change along the vehicle.

The models' meshes face -Y (studiomdl's default rotation turns them to +X in game), so "along the vehicle" = mesh -y.
Scale sign: the bottom run stands on the ground, so relative to the hull it runs backwards as the vehicle drives
forward. A mark painted on it at coordinate c(f) under hull point f is, after driving d, under hull point f - d, where
the mesh's own coordinate is c(f) - g d (g = d(coord)/d(forward) on the bottom run). The shader samples mesh
coordinate + offset, so to show the mark there: offset = g x d. Checked on numbers (halftrack, g = -0.043: drive 10,
the mark sits at f = -10 where the mesh says c + 0.43, so the offset is -0.43 = g x d). So the proxy's "scale"
(DoDSPTrackScroll: offset = distance driven x scale) is g, signed. The top run gives the same within the measured
spread (it runs the other way along the loop). Prints, per model, every material it judged.
"""
import os, sys, numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from editor_models import mesh

STEADY = 0.6          # a run's triangles agree on the sign of the gradient at least this often
MIN_RATE = 0.002      # texture repeats per unit: below this the axis doesn't run along the vehicle

def judge(mdl):
    tris, _ = mesh(mdl)
    zs = np.array([p[2] for _, vs in tris for p, n, uv in vs])
    floor = zs.min()
    by = {}
    for mat, vs in tris:
        P = np.array([p for p, n, uv in vs]); UV = np.array([uv for p, n, uv in vs])
        if np.ptp(P[:, 1]) < 3.0: continue                       # only faces that run along the vehicle
        G, *_ = np.linalg.lstsq(np.array([P[1] - P[0], P[2] - P[0]]), np.array([UV[1] - UV[0], UV[2] - UV[0]]), rcond=None)
        z = P[:, 2].mean() - floor
        # forward = -mesh y, so d/d(forward) = -d/dy
        by.setdefault(mat.lower(), []).append((z, -G[1, 0], -G[1, 1], np.sign(P[:, 0].mean())))
    out = []
    for mat, rows in sorted(by.items()):
        R = np.array(rows)
        zmax = R[:, 0].max()
        bottom = R[R[:, 0] < 8.0]                                # on the ground
        top = R[R[:, 0] > max(0.6 * zmax, 16.0)] if zmax > 16 else R[:0]
        best = None
        for k, ax in ((1, 'u'), (2, 'v')):
            if len(bottom) < 6 or len(top) < 6: continue
            gb, gt = np.median(bottom[:, k]), np.median(top[:, k])
            agree_b = np.mean(np.sign(bottom[:, k]) == np.sign(gb)); agree_t = np.mean(np.sign(top[:, k]) == np.sign(gt))
            sides = len(set(bottom[:, 3])) == 2
            loop = abs(gb) > MIN_RATE and abs(gt) > MIN_RATE and np.sign(gb) != np.sign(gt) and agree_b >= STEADY and agree_t >= STEADY
            if loop and (best is None or abs(gb) > abs(best[1])):
                best = (ax, gb, gt, agree_b, agree_t, sides)
        out.append((mat, len(rows), best))
    return out

def write_table(d, models, out):
    """one entry per track material (several variants share one): the same material must measure the same everywhere"""
    table = {}
    for m in models:
        for mat, n, best in judge(os.path.join(d, m)):
            if not best: continue
            ax, gb = best[0], best[1]
            if mat in table and (table[mat][0] != ax or abs(table[mat][1] - gb) > 0.01 * abs(gb)):
                raise SystemExit('%s measures %s %.5f on %s but %s %.5f on %s' % (mat, ax, gb, m, table[mat][0], table[mat][1], table[mat][2]))
            table.setdefault(mat, (ax, gb, m))
    lines = ['// GENERATED by dodsp_tools/vehicle_preview/tread_scroll.py from the vehicle models - do not edit by hand.',
             '// Which materials are vehicle TRACKS, the texture axis that runs along them, and texture repeats per unit driven',
             '// (signed: the bottom run stands on the ground). Read by client.dll (c_dodsp_vehicle.cpp DoDSPTrackScroll).',
             '"DoDSPTreads"', '{']
    for mat in sorted(table):
        ax, sc, m = table[mat]
        lines.append('\t"%s"\t{ "axis" "%s"  "scale" "%.5f" }\t// %s' % (mat, ax, sc, m[:-4]))
    lines.append('}')
    open(out, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote %d track materials to %s' % (len(table), out))

if __name__ == '__main__':
    d = sys.argv[1]
    if len(sys.argv) > 3 and sys.argv[2] == '--write':
        write_table(d, sorted(f for f in os.listdir(d) if f.endswith('.mdl') and '_dead' not in f and '_turret' not in f), sys.argv[3])
        sys.exit(0)
    models = sys.argv[2:] or sorted(f for f in os.listdir(d) if f.endswith('.mdl') and '_dead' not in f and '_turret' not in f)
    for m in models:
        res = judge(os.path.join(d, m if m.endswith('.mdl') else m + '.mdl'))
        tracks = [r for r in res if r[2]]
        print('%s: %s' % (m, ', '.join(r[0] for r in tracks) or 'NO TRACK MATERIAL'))
        for mat, n, best in res:
            if best:
                ax, gb, gt, ab, at, sides = best
                print('  TRACK %-34s axis %s  bottom %+.5f/unit  top %+.5f  (agree %.0f%% / %.0f%%%s)  -> "scale" "%.4f"' % (
                    mat, ax, gb, gt, 100 * ab, 100 * at, '' if sides else ', ONE SIDE ONLY', gb))
            else:
                print('  not a track: %s (%d faces along the vehicle)' % (mat, n))
